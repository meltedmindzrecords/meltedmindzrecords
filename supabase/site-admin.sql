-- 2) Artist page addresses: old slugs are remembered so old links redirect.
alter table public.artists add column if not exists previous_slugs text[] not null default '{}';
create or replace function public.artists_keep_old_slug() returns trigger language plpgsql as $f$
begin
  if new.slug is distinct from old.slug and old.slug is not null and old.slug <> '' then
    new.previous_slugs := array_remove(array_append(array_remove(coalesce(new.previous_slugs, '{}'), old.slug), old.slug), new.slug);
  end if;
  return new;
end $f$;
drop trigger if exists artists_keep_old_slug on public.artists;
create trigger artists_keep_old_slug before update of slug on public.artists
  for each row execute function public.artists_keep_old_slug();

