create or replace function public.log_site_change() returns trigger
language plpgsql security definer set search_path = public as $f$
declare
  rec jsonb;
  prev jsonb;
  who text;
  label text;
  changed text[] := '{}';
  act text;
begin
  begin
    if tg_op = 'DELETE' then rec := to_jsonb(old); else rec := to_jsonb(new); end if;
    if tg_op = 'UPDATE' then
      prev := to_jsonb(old);
      if tg_table_name = 'site_settings' then
        select coalesce(array_agg(k order by k), '{}') into changed from (
          select k from jsonb_object_keys(coalesce(new.data, '{}'::jsonb) || coalesce(old.data, '{}'::jsonb)) as k
          where (new.data -> k) is distinct from (old.data -> k)) s;
      else
        select coalesce(array_agg(key order by key), '{}') into changed from jsonb_each(rec) e
          where key not in ('updated_at', 'created_at', 'previous_slugs') and (prev -> key) is distinct from e.value;
      end if;
      if array_length(changed, 1) is null then return null; end if;
      act := case when changed = array['sort_order'] then 'reorder' else 'update' end;
    else
      act := lower(tg_op);
      if tg_op = 'INSERT' then act := 'create'; end if;
    end if;
    select m.email into who from public.portal_members m where m.user_id = auth.uid() limit 1;
    label := coalesce(rec ->> 'name', rec ->> 'title', rec ->> 'email', case when tg_table_name = 'site_settings' then 'Site settings' end);
    insert into public.admin_activity (user_id, actor, action, area, item_id, item_label, changes)
    values (auth.uid(), coalesce(who, case when auth.uid() is null then 'database' else 'unknown' end),
            act, tg_table_name, rec ->> 'id', label, changed);
  exception when others then
    raise warning 'activity log skipped: %', sqlerrm;
  end;
  return null;
end $f$;
revoke all on function public.log_site_change() from public, anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array['artists','releases','news','team','listings','site_settings'] loop
    execute format('drop trigger if exists log_site_change on public.%I', t);
    execute format('create trigger log_site_change after insert or update or delete on public.%I for each row execute function public.log_site_change()', t);
  end loop;
  execute 'drop trigger if exists log_site_change on public.newsletter_subscribers';
  execute 'create trigger log_site_change after delete on public.newsletter_subscribers for each row execute function public.log_site_change()';
end $$;
