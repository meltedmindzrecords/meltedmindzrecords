-- Website admin (/admin): news table, admin-only writes, site-images uploads.
-- Applied to project zgjadklledqbldrmyymy on 2026-11-12. Safe to re-run.

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  slug text,
  title text not null,
  category text not null default 'Press Release',
  published_on date,
  description text,
  link_url text,
  image_url text,
  sort_order integer not null default 100,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.news enable row level security;
grant select on public.news to anon, authenticated;
grant insert, update, delete on public.news to authenticated;
grant usage, select on sequence public.news_id_seq to authenticated;
drop policy if exists "Public can read visible news" on public.news;
create policy "Public can read visible news" on public.news for select to anon, authenticated using (visible = true);

do $$
declare t text;
begin
  foreach t in array array['artists','releases','team','news'] loop
    execute format('drop policy if exists "Site admins read all %1$s" on public.%1$I', t);
    execute format('create policy "Site admins read all %1$s" on public.%1$I for select to authenticated using (public.portal_is_admin())', t);
    execute format('drop policy if exists "Site admins insert %1$s" on public.%1$I', t);
    execute format('create policy "Site admins insert %1$s" on public.%1$I for insert to authenticated with check (public.portal_is_admin())', t);
    execute format('drop policy if exists "Site admins update %1$s" on public.%1$I', t);
    execute format('create policy "Site admins update %1$s" on public.%1$I for update to authenticated using (public.portal_is_admin()) with check (public.portal_is_admin())', t);
    execute format('drop policy if exists "Site admins delete %1$s" on public.%1$I', t);
    execute format('create policy "Site admins delete %1$s" on public.%1$I for delete to authenticated using (public.portal_is_admin())', t);
    execute format('grant insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

create or replace function public.cms_touch_updated_at() returns trigger language plpgsql as $f$
begin new.updated_at = now(); return new; end $f$;
do $$
declare t text;
begin
  foreach t in array array['artists','releases','team','news'] loop
    execute format('drop trigger if exists cms_touch_%1$s on public.%1$I', t);
    execute format('create trigger cms_touch_%1$s before update on public.%1$I for each row execute function public.cms_touch_updated_at()', t);
  end loop;
end $$;

-- Storage: public site-images bucket, writes for portal admins only
update storage.buckets set public = true where id = 'site-images';
drop policy if exists "site images admin insert" on storage.objects;
create policy "site images admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'site-images' and public.portal_is_admin());
drop policy if exists "site images admin update" on storage.objects;
create policy "site images admin update" on storage.objects for update to authenticated using (bucket_id = 'site-images' and public.portal_is_admin()) with check (bucket_id = 'site-images' and public.portal_is_admin());
drop policy if exists "site images admin delete" on storage.objects;
create policy "site images admin delete" on storage.objects for delete to authenticated using (bucket_id = 'site-images' and public.portal_is_admin());
drop policy if exists "site images admin select" on storage.objects;
create policy "site images admin select" on storage.objects for select to authenticated using (bucket_id = 'site-images' and public.portal_is_admin());
